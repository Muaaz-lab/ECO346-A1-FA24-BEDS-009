import os
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.ticker import FixedLocator, FuncFormatter, NullLocator

# Create figures directory if it doesn't exist
os.makedirs("figures", exist_ok=True)

VARIANT = 1                                          # <- last two digits of reg. no. % 8
prov = [2, 2, 3, 3, 1, 1, 4, 4][VARIANT]
area = [1, 2, 1, 2, 1, 2, 1, 2][VARIANT]

# Read files directly from /content/
person = pd.read_csv("pslm_person_subset.csv", usecols=["hhid", "age", "earn_annual"])
hh = pd.read_csv("pslm_hh_subset.csv", usecols=["hhid", "hhweight", "prov_code", "urban_rural"])

d = person.merge(hh, on="hhid", how="inner")         # attach weight, province, area
d = d[(d.age >= 15) & (d.age <= 64) & (d.earn_annual > 0)
      & (d.prov_code == prov) & (d.urban_rural == area)].copy()

# Five-year bands, plotted at the midpoint; thin = fewer than 30 earners.
d["band_start"] = 5 * (d.age // 5)
rows = []
for b, g in d.groupby("band_start"):
    wmean = (g.hhweight * g.earn_annual).sum() / g.hhweight.sum()   # weighted mean
    rows.append((b, f"{b}-{b + 4}", len(g), int(round(wmean)), len(g) < 30))
bands = pd.DataFrame(rows, columns=["band_start", "band", "n", "wmean", "thin"])
bands["mid"] = bands.band_start + 2
bands[["band", "n", "wmean"]].to_csv("figures/band_table_python.csv", index=False)
print(bands[["band", "n", "wmean", "thin"]].to_string(index=False))

# Check against the R table, if it has been produced.
try:
    r = pd.read_csv("figures/band_table_R.csv")
    same = (r.band.values == bands.band.values).all() and (r.wmean.values == bands.wmean.values).all()
    print("Band tables agree with R to the rupee:", same)
except FileNotFoundError:
    print("Run scripts/03_relationship.R first to compare with R.")

top = bands.loc[bands.wmean.idxmax()]
rng = np.random.default_rng(346)                     # fixed seed (jitter)
jit = d.age + rng.uniform(-0.4, 0.4, len(d))         # at most 0.4 years, horizontal only
n_off = int(((d.earn_annual < 1e4) | (d.earn_annual > 1e7)).sum())

fig, ax = plt.subplots(figsize=(8, 5))
ax.scatter(jit, d.earn_annual, s=4, color="0.25", alpha=0.15, linewidths=0)   # matplotlib default adds edges: removed
ax.plot(bands.mid, bands.wmean, color="#c0392b", lw=1.8)
full, thin = bands[~bands.thin], bands[bands.thin]
ax.scatter(full.mid, full.wmean, s=45, color="#c0392b", zorder=3)
ax.scatter(thin.mid, thin.wmean, s=45, facecolors="white", edgecolors="#c0392b", linewidths=1.5, zorder=3)
ax.annotate(f"Highest: ages {top.band}\nRs {top.wmean:,.0f}", (top.mid, top.wmean),
            xytext=(top.mid, top.wmean * 1.9), ha="center", fontsize=9,
            bbox=dict(boxstyle="round", fc="white", ec="0.5"), arrowprops=dict(arrowstyle="-", color="0.5"))

ax.set_yscale("log")
ax.set_ylim(1e4, 1e7)
ax.yaxis.set_major_locator(FixedLocator([1e4, 1e5, 1e6, 1e7]))
ax.yaxis.set_minor_locator(NullLocator())
ax.yaxis.set_major_formatter(FuncFormatter(lambda v, _: f"Rs {v:,.0f}"))   # rupees, not 10^4
ax.set_xlim(14.5, 64.5)
ax.set_xticks(range(15, 66, 5))
ax.set_xlabel("Age (years)")
ax.set_ylabel("Annual earnings (log scale)")
ax.set_title(f"Mean earnings rise with age and peak at {top.band}", loc="left", fontweight="bold")
for side in ("top", "right"):
    ax.spines[side].set_visible(False)
ax.grid(axis="y", color="0.9")
ax.set_axisbelow(True)
fig.text(0.01, 0.01,
         f"Source: PSLM 2019-20. Sample: earners aged 15-64 with earnings > 0 in my variant (n = {len(d)}). "
         f"Weighted by hhweight (band means only).\nHollow markers: band with fewer than 30 earners. "
         f"{n_off} points outside the axis range are not shown.", fontsize=7, ha="left", va="bottom")
fig.tight_layout(rect=(0, 0.06, 1, 1))
fig.savefig("figures/relationship_python.svg")

